@mcp.tool()
async def view_appointments(patient_id: str, ctx: Context) -> dict:
    """View appointments for a patient."""
    context_message = f"Viewing appointments for patient: {patient_id}"
    await ctx.info(context_message)
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("""
        SELECT *
        FROM appointments
        WHERE patient_id = ?
        ORDER BY date, time
    """, (patient_id,))

    rows = cur.fetchall()
    conn.close()

    return {
        "success": True,
        "appointments": [dict(row) for row in rows],
        "runtime_context": [context_message]
    }

@mcp.resource("appointments://{patient_id}/context")
def appointment_context(patient_id: str) -> str:
    """Return a compact appointment context summary for an MCP client."""
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("""
        SELECT *
        FROM appointments
        WHERE patient_id = ?
        ORDER BY date, time
    """, (patient_id,))

    rows = cur.fetchall()
    conn.close()

    if not rows:
        return f"No appointment context found for patient ID {patient_id}."

    appointment_lines = [
        (
            f"- {row['appointment_id']}: {row['date']} at {row['time']} "
            f"with {row['provider']} ({row['status']})"
        )
        for row in rows
    ]

    return "Appointment Context\n\n" + "\n".join(appointment_lines)


if __name__ == "__main__":
    mcp.run()
