@mcp.resource("patient://{patient_id}/context")
def patient_context(patient_id: str) -> str:
    """Return a compact patient context summary for an MCP client."""
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("SELECT * FROM patients WHERE patient_id = ?", (patient_id,))
    patient = cur.fetchone()

    cur.execute("SELECT * FROM insurance_records WHERE patient_id = ?", (patient_id,))
    insurance = cur.fetchone()

    conn.close()

    if not patient:
        return f"No patient context found for patient ID {patient_id}."

    insurance_summary = "No insurance record on file."
    if insurance:
        insurance_summary = (
            f"Insurance: {insurance['provider']}, "
            f"member ID {insurance['member_id']}, "
            f"group {insurance['group_number']}."
        )

    return f"""
Patient Context

Patient ID: {patient['patient_id']}
Name: {patient['full_name']}
DOB: {patient['dob']}
Phone: {patient['phone']}
Email: {patient['email']}
{insurance_summary}
"""

def is_washington_resident(state: str) -> bool:
    if not state:
        return False

    normalized = state.strip().lower()
    return normalized in {"wa", "washington"}

def calculate_age(dob: str) -> int:
    birth_date = datetime.strptime(dob, "%m/%d/%Y").date()

    today = date.today()

    return (
        today.year
        - birth_date.year
        - ((today.month, today.day) <
           (birth_date.month, birth_date.day))
    )

